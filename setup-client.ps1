param(
    [switch]$InstallOnly
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$RepoRoot = $PSScriptRoot
if (-not $RepoRoot) {
    $RepoRoot = (Get-Location).Path
}

Set-Location $RepoRoot

$VenvDir = Join-Path $RepoRoot ".venv"
$VenvPython = Join-Path $VenvDir "Scripts\python.exe"
$EnvFile = Join-Path $RepoRoot ".env"

function Write-Section {
    param([string]$Message)
    Write-Host ""
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Test-PythonCandidate {
    param(
        [string]$CommandName,
        [string[]]$CommandArgs = @()
    )

    $exists = $false
    if ($CommandName -match '[\\/]') {
        $exists = Test-Path $CommandName
    } else {
        $exists = [bool](Get-Command $CommandName -ErrorAction SilentlyContinue)
    }

    if (-not $exists) {
        return $null
    }

    try {
        $versionText = & $CommandName @CommandArgs --version 2>&1
        if ($LASTEXITCODE -ne 0 -or -not $versionText) {
            return $null
        }
        if ($versionText -notmatch '^Python (\d+)\.(\d+)\.(\d+)') {
            return $null
        }

        $major = [int]$matches[1]
        $minor = [int]$matches[2]
        if ($major -ne 3 -or $minor -lt 11) {
            return $null
        }

        $exe = & $CommandName @CommandArgs -c "import sys; print(sys.executable)" 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $exe) {
            return $null
        }

        return [pscustomobject]@{
            Command = $CommandName
            Args    = $CommandArgs
            Exe     = $exe.Trim()
            Version = $versionText.Trim()
        }
    } catch {
        return $null
    }
}

function Get-PythonFromCommonPaths {
    $programFilesX86 = ${env:ProgramFiles(x86)}
    $paths = @(
        Join-Path $env:LocalAppData "Programs\Python\Python311\python.exe"
        Join-Path $env:LocalAppData "Programs\Python\Python312\python.exe"
        Join-Path $env:LocalAppData "Programs\Python\Python313\python.exe"
        Join-Path $env:ProgramFiles "Python311\python.exe"
        Join-Path $env:ProgramFiles "Python312\python.exe"
        Join-Path $env:ProgramFiles "Python313\python.exe"
    )

    if ($programFilesX86) {
        $paths += @(
            Join-Path $programFilesX86 "Python311\python.exe"
            Join-Path $programFilesX86 "Python312\python.exe"
            Join-Path $programFilesX86 "Python313\python.exe"
        )
    }

    foreach ($path in $paths) {
        if (-not (Test-Path $path)) {
            continue
        }

        $candidate = Test-PythonCandidate -CommandName $path
        if ($candidate) {
            return $candidate
        }
    }

    return $null
}

function Resolve-Python {
    $checks = @(
        @{ Command = "python"; Args = @() }
        @{ Command = "py"; Args = @("-3.11") }
        @{ Command = "py"; Args = @("-3.12") }
        @{ Command = "py"; Args = @("-3.13") }
        @{ Command = "py"; Args = @("-3") }
    )

    foreach ($check in $checks) {
        $candidate = Test-PythonCandidate -CommandName $check.Command -CommandArgs $check.Args
        if ($candidate) {
            return $candidate
        }
    }

    return Get-PythonFromCommonPaths
}

function Install-Python311 {
    if (-not (Get-Command winget -ErrorAction SilentlyContinue)) {
        throw "Python 3.11 is not installed and winget is not available. Install Python from https://www.python.org/downloads/windows/ and rerun this script."
    }

    Write-Section "Installing Python 3.11"
    & winget install --id Python.Python.3.11 -e --source winget --scope user --silent --accept-package-agreements --accept-source-agreements
    if ($LASTEXITCODE -ne 0) {
        throw "winget could not install Python 3.11. Install Python manually and rerun this script."
    }
}

function Ensure-EnvFile {
    if (Test-Path $EnvFile) {
        return
    }

    Write-Section "Creating local .env file"
    $secretKey = [guid]::NewGuid().ToString("N")
    @(
        "# Auto-generated by setup-client.ps1"
        "SECRET_KEY=$secretKey"
        "FLASK_DEBUG=0"
        "HOST=0.0.0.0"
        "PORT=5000"
    ) | Set-Content -Path $EnvFile -Encoding ASCII
}

function Ensure-Venv {
    if (Test-Path $VenvPython) {
        Write-Host "Using existing virtual environment at $VenvDir"
        return
    }

    Write-Section "Creating virtual environment"
    $python = Resolve-Python
    if (-not $python) {
        Install-Python311
        $python = Resolve-Python
    }

    if (-not $python) {
        throw "Could not find a working Python 3.11+ installation after setup."
    }

    $pythonArgs = @($python.Args)
    & $python.Command @pythonArgs -m venv $VenvDir
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to create the virtual environment."
    }
}

function Install-Requirements {
    Write-Section "Installing project dependencies"
    & $VenvPython -m pip install --upgrade pip setuptools wheel
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to upgrade pip inside the virtual environment."
    }

    & $VenvPython -m pip install --prefer-binary -r (Join-Path $RepoRoot "requirements.txt")
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to install project dependencies."
    }
}

Write-Section "Bootstrapping QuickEats"

$python = Resolve-Python
if (-not $python) {
    Install-Python311
    $python = Resolve-Python
}

if (-not $python) {
    throw "Could not find a working Python 3.11+ installation after setup."
}

Write-Host "Python found: $($python.Version)"

Ensure-EnvFile
Ensure-Venv
Install-Requirements

if ($InstallOnly) {
    Write-Host ""
    Write-Host "Setup complete. To start the app later, run setup-client.ps1 without -InstallOnly."
    exit 0
}

Write-Section "Starting the app"
Write-Host "Open http://127.0.0.1:5000 in your browser after the server finishes starting."
& $VenvPython (Join-Path $RepoRoot "run.py")
